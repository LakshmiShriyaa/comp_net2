import xml.etree.ElementTree as ET
from pathlib import Path
import numpy as np
import pandas as pd

# Folder containing your extracted XML files
data_folder = Path("/content/traffic_data/traffic-matrices")

xml_files = sorted(data_folder.glob("*.xml"))

print("Total XML files:", len(xml_files))

# Inspect the first file to get the node IDs
root = ET.parse(xml_files[0]).getroot()
tm = root.find(".//IntraTM")

node_ids = sorted(
    {src.attrib["id"] for src in tm.findall("src")},
    key=int
)

print("Number of source nodes:", len(node_ids))
print("Node IDs:", node_ids)

# Create a matrix from each XML file
matrices = []
timestamps = []

for i, file in enumerate(xml_files):
    root = ET.parse(file).getroot()
    tm = root.find(".//IntraTM")

    matrix = np.full(
        (len(node_ids), len(node_ids)),
        np.nan,
        dtype=np.float32
    )

    for src in tm.findall("src"):
        src_id = src.attrib["id"]

        for dst in src.findall("dst"):
            dst_id = dst.attrib["id"]

            r = node_ids.index(src_id)
            c = node_ids.index(dst_id)
            matrix[r, c] = float(dst.text)

    matrices.append(matrix)
    timestamps.append(
        tm.get("date") or root.findtext(".//date")
    )

    if (i + 1) % 1000 == 0:
        print("Processed:", i + 1)

matrices = np.stack(matrices)

print("\nConversion complete!")
print("Matrix array shape:", matrices.shape)
print("Missing values:", np.isnan(matrices).sum())
print("First timestamp:", timestamps[0])

